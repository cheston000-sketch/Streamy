import assert from 'node:assert/strict';
import {webcrypto} from 'node:crypto';
import {PARENT_PIN_KEY,PARENT_PIN_ATTEMPTS_KEY,hasParentPin,isValidParentPin,setParentPin,verifyParentPin,removeParentPin} from '../www/js/parent-pin.js';
if (!globalThis.crypto) Object.defineProperty(globalThis,'crypto',{value:webcrypto,configurable:true});
const data=new Map();const store={getItem:k=>data.has(k)?data.get(k):null,setItem:(k,v)=>data.set(k,v),removeItem:k=>data.delete(k)};
assert.equal(hasParentPin(store),false);
for(const invalid of ['12','1234567','a123','12 34','']) assert.equal(isValidParentPin(invalid),false);
assert.equal(isValidParentPin('0000'),true);
await assert.rejects(()=>setParentPin('12',store),/4 to 6 digits/);
await setParentPin('4821',store);
assert.equal(hasParentPin(store),true);
assert.ok(!data.get(PARENT_PIN_KEY).includes('4821'),'the PIN must never be stored in plaintext');
assert.equal((await verifyParentPin('4821',store)).ok,true);
for(let i=0;i<4;i++)assert.equal((await verifyParentPin('9999',store,1000)).ok,false);
assert.equal((await verifyParentPin('9999',store,1000)).locked,true);
assert.deepEqual(await verifyParentPin('4821',store,1001),{ok:false,locked:true});
assert.equal((await verifyParentPin('4821',store,61001)).ok,true);
assert.equal(data.has(PARENT_PIN_ATTEMPTS_KEY),false);
const before=data.get(PARENT_PIN_KEY);assert.equal(await setParentPin('1234',store,{shouldCommit:()=>false}),false);
assert.equal(data.get(PARENT_PIN_KEY),before,'cancelling a pending change must preserve the PIN');
data.set(PARENT_PIN_KEY,'bad');
assert.equal(hasParentPin(store),true);
await assert.rejects(()=>verifyParentPin('4821',store),/PIN data is unavailable/);
removeParentPin(store);assert.equal(hasParentPin(store),false);
console.log('Parent PIN protection tests passed.');
